// Renders a small "markdown-lite" subset: **bold** segments only.
// Used throughout guide content so data files can use **bold** for emphasis
// without needing a full markdown renderer.
export default function FormattedText({ text }: { text: string }) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return (
    <>
      {parts.map((part, i) => {
        if (part.startsWith("**") && part.endsWith("**")) {
          return <strong key={i}>{part.slice(2, -2)}</strong>;
        }
        return <span key={i}>{part}</span>;
      })}
    </>
  );
}
